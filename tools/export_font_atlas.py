"""Turns the HUD fonts into image sheets, because Roblox can't import font files.

Run: python tools/export_font_atlas.py <folder holding the unpacked fonts>
Writes assets/hud/<style>.png and src/shared/Guns/Hud/GlyphData.luau.
Upload any changed sheet and put its id in src/shared/Guns/Hud/FontImages.luau.
"""
import glob
import os
import string
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SHEET_DIR = os.path.join(ROOT, "assets", "hud")
DATA_PATH = os.path.join(ROOT, "src", "shared", "Guns", "Hud", "GlyphData.luau")

SHEET = 1024
PADDING = 4
LABEL_CHARACTERS = string.ascii_uppercase + string.digits + "/:.->+"

# Style: font file pattern, characters, size the glyphs are drawn at.
STYLES = {
    "Number": ("KHInterference*-Bold.otf", string.digits + "/+", 138),
    "NumberThin": ("KHInterference*-Light.otf", string.digits + "+", 138),
    "Title": ("KHInterference*-Bold.otf", string.ascii_uppercase, 180),
    "Label": ("PPFraktionMono-Regular.otf", LABEL_CHARACTERS, 36),
    "LabelBold": ("PPFraktionMono-Bold.otf", LABEL_CHARACTERS, 36),
}


def find_font(folder, pattern):
    found = glob.glob(os.path.join(folder, "**", pattern), recursive=True)
    if not found:
        sys.exit(f"No font matching {pattern} under {folder}")
    return found[0]


def pack(font, characters):
    """Lays the glyphs out in rows and draws them on one sheet."""
    sheet = Image.new("RGBA", (SHEET, SHEET), (255, 255, 255, 0))
    draw = ImageDraw.Draw(sheet)
    glyphs = {}
    x, y, row = PADDING, PADDING, 0
    for character in characters:
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        width, height = right - left, bottom - top
        if x + width + PADDING > SHEET:
            x, y, row = PADDING, y + row + PADDING, 0
        if y + height + PADDING > SHEET:
            sys.exit("Glyphs don't fit on the sheet")
        draw.text((x - left, y - top), character, font=font, fill=(255, 255, 255, 255), anchor="ls")
        glyphs[character] = {
            "x": x,
            "y": y,
            "w": width,
            "h": height,
            "ox": left,
            "oy": top,
            "advance": round(font.getlength(character), 2),
        }
        x += width + PADDING
        row = max(row, height)
    return sheet, glyphs


def luau_key(character):
    return '["' + character.replace("\\", "\\\\").replace('"', '\\"') + '"]'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    folder = sys.argv[1]
    os.makedirs(SHEET_DIR, exist_ok=True)
    os.makedirs(os.path.dirname(DATA_PATH), exist_ok=True)
    lines = ["-- Generated by tools/export_font_atlas.py. Don't edit by hand.", "return {"]
    for style, (pattern, characters, source) in STYLES.items():
        font = ImageFont.truetype(find_font(folder, pattern), source)
        sheet, glyphs = pack(font, characters)
        sheet.save(os.path.join(SHEET_DIR, f"{style}.png"))
        lines.append(f"\t{style} = {{")
        lines.append(f'\t\tsheet = "{style}",')
        lines.append(f"\t\tsource = {source},")
        lines.append(f'\t\tspace = {round(font.getlength(" "), 2)},')
        lines.append("\t\tglyphs = {")
        for character in sorted(glyphs):
            fields = ", ".join(f"{key} = {value}" for key, value in glyphs[character].items())
            lines.append(f"\t\t\t{luau_key(character)} = {{ {fields} }},")
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    with open(DATA_PATH, "w", encoding="utf8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
